const { chromium } = require('playwright');
const URL = 'file://' + __dirname + '/../dist/preview.html';
(async () => { const b = await chromium.launch(); const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
  const A = await c.newPage(), B = await c.newPage();
  const errs = []; for (const p of [A, B]) p.on('pageerror', (e) => errs.push(e.message));
  await A.goto(URL + '#nemo'); await A.click('button:text-is("온라인 경주")'); await A.fill('#nemo-nick', '현진');
  await A.click('button:text-is("온라인 방 만들기")'); await A.waitForSelector('.lobby .code-tiles');
  const code = await A.getAttribute('.lobby .code-tiles', 'data-code');
  const seats0 = await A.$$eval('.seats .seat', (s) => s.map((x) => x.className.replace('seat', '').trim() || 'filled'));
  await A.screenshot({ path: process.argv[2] + '/lobby-host-empty.png' });
  await B.goto(URL + '#nemo'); await B.click('button:text-is("온라인 경주")'); await B.fill('#nemo-nick', '친구');
  await B.fill('#nemo-code', code); await B.click('button:text-is("참가하기")');
  await A.waitForFunction(() => document.querySelectorAll('.seats .seat:not(.empty)').length === 2, null, { timeout: 8000 });
  await A.waitForTimeout(150);
  const toast = await A.textContent('#toast');
  const popped = await A.$$eval('.seats .seat.pop .seat-name', (s) => s.map((x) => x.textContent));
  await B.waitForSelector('.lobby .room-made');
  console.log('host head:', await A.textContent('.room-made-head'), '| guest head:', await B.textContent('.room-made-head'));
  console.log('seats before:', seats0.join(','), '| after join names:', await A.$$eval('.seats .seat-name', (s) => s.map((x) => x.textContent)), '| pop:', popped, '| toast:', toast);
  console.log('guest sees:', await B.$$eval('.seats .seat', (s) => s.map((x) => x.querySelector('.seat-no').textContent + ':' + (x.querySelector('.seat-name')?.textContent || '빈자리') + (x.classList.contains('me') ? '(나)' : ''))));
  await A.click('button:text-is("+ 컴퓨터")');
  await B.waitForFunction(() => document.querySelectorAll('.seats .seat:not(.empty)').length === 3);
  await A.screenshot({ path: process.argv[2] + '/lobby-host.png', fullPage: true });
  await B.screenshot({ path: process.argv[2] + '/lobby-guest.png' });
  await B.click('button:text-is("나가기")');
  await A.waitForFunction(() => document.querySelectorAll('.seats .seat:not(.empty)').length === 2, null, { timeout: 8000 });
  await A.waitForTimeout(150);
  console.log('after leave toast:', await A.textContent('#toast'), '| overflow:', await A.evaluate(() => document.documentElement.scrollWidth));
  console.log('errors', errs.length ? errs : 'none');
  await b.close(); })();
